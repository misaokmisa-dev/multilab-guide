#!/usr/bin/env python3
"""Synchronize Minecraft item-page search titles with actual crafting recipes.

The site has 1,504 pre-rendered HTML pages and 168 query-driven new items.
SEO-critical <title> and og:title must exist in the served HTML, not only JS.
Crafting-table recipe -> 【マイクラ】 ○○の作り方と使い方
No crafting-table recipe -> 【マイクラ】 ○○の入手方法
"""
from __future__ import annotations

import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ITEMS = ROOT / "minecraft/strategy/items"
DETAILS = ITEMS / "detail"


def js_data(filename: str, variable: str):
    source = (ITEMS / filename).read_text(encoding="utf-8")
    match = re.search(r"window\." + re.escape(variable) + r"\s*=\s*", source)
    if not match:
        raise ValueError(f"Cannot locate {variable} in {filename}")
    return json.loads(source[match.end():].strip().removesuffix(";"))


def change_title(path: Path, title: str) -> bool:
    source = path.read_text(encoding="utf-8")
    safe_text = html.escape(title, quote=False)
    safe_attribute = html.escape(title, quote=True)
    updated, title_count = re.subn(
        r"<title>[^<]*</title>",
        lambda _: f"<title>{safe_text}</title>",
        source,
        count=1,
    )
    updated, og_count = re.subn(
        r'<meta\s+property="og:title"\s+content="[^"]*"',
        lambda _: f'<meta property="og:title" content="{safe_attribute}"',
        updated,
        count=1,
    )
    if title_count != 1 or og_count != 1:
        raise ValueError(f"Expected exactly one title and og:title: {path}")
    if updated == source:
        return False
    path.write_text(updated, encoding="utf-8")
    return True


def build_new_item_page(template: str, item, category_names: dict[str, str], recipes: dict) -> str:
    """Build a crawlable static HTML page for a 2026 item using the existing UI."""
    item_id, slug, name, english, category, _stack, version = item
    if not re.fullmatch(r"[a-z0-9_]+", slug):
        raise ValueError(f"Invalid item slug: {slug}")
    source = template.replace(
        "<head>", "<head><!-- Generated by scripts/update_item_seo_titles.py -->", 1
    )
    source = source.replace('data-item=""', f'data-item="{slug}"', 1)
    category_label = category_names[category]
    source = source.replace(
        'href="/minecraft/strategy/items/category/tools.html">アイテム詳細',
        f'href="/minecraft/strategy/items/category/{category}.html">{html.escape(category_label)}',
    )
    source = source.replace(" › 追加アイテム</nav>", " › " + html.escape(name) + "</nav>")
    source = source.replace(
        '<link rel="canonical" href="https://mlabg.com/minecraft/strategy/items/detail/new.html">',
        f'<link rel="canonical" href="https://mlabg.com/minecraft/strategy/items/detail/{slug}.html">',
    )
    has_craft = bool(recipes.get(str(item_id)))
    method = "作り方と使い方" if has_craft else "入手方法"
    description = (f"【マイクラ】{name}（{english}）の{method}を紹介。"
                   f"Minecraft Java {version}の情報を掲載。")
    for attr in ('name="description"', 'property="og:description"'):
        source, count = re.subn(
            r'(<meta\s+' + re.escape(attr) + r'\s+content=")[^"]*(")',
            lambda m: m[1] + html.escape(description, quote=True) + m[2],
            source,
            count=1,
        )
        if count != 1:
            raise ValueError(f"Could not update {attr} for {slug}")

    fallback = (
        '<div id="ency-detail"><section class="ency-detail-hero"><div>'
        '<span class="ency-kicker">MINECRAFT / ' + html.escape(category_label) + '</span>'
        '<h1 id="ency-hero-name">' + html.escape(name) + '</h1>'
        '<p class="ency-en">' + html.escape(english) + '</p></div></section>'
        '<section class="ency-panel"><h2>概要</h2><p>'
        + html.escape(name) + '（' + html.escape(english) + '）の'
        + method + 'を解説するページです。詳細を読み込んでいます。'
        '</p></section></div>'
    )
    previous = '<div id="ency-detail"><p>アイテムの詳細データを読み込んでいます。</p></div>'
    if previous not in source or 'data-item="' + slug + '"' not in source:
        raise ValueError(f"Item template changed unexpectedly: {slug}")
    source = source.replace(previous, fallback, 1)
    return source


def main() -> None:
    old = js_data("items-data.js", "MLG_ITEMS")["items"]
    new = js_data("items-2026-data.js", "MLG_ITEM_ADDITIONS")["items"]
    recipes = js_data("recipes-data.js", "MLG_RECIPES")
    recipes.update(js_data("recipes-2026-data.js", "MLG_RECIPES_2026"))
    if len(old) != 1504 or len(new) != 168:
        raise ValueError(f"Unexpected item registry size: {len(old)}+{len(new)}")
    if len({item[1] for item in old + new}) != 1672:
        raise ValueError("Item slugs are not unique")

    changed = created = obtained = 0
    missing = []
    for item_id, slug, japanese_name, *_ in old:
        has_craft = bool(recipes.get(str(item_id)))
        title = ("【マイクラ】 " + japanese_name
                 + ("の作り方と使い方" if has_craft else "の入手方法"))
        path = DETAILS / (slug + ".html")
        if not path.is_file():
            missing.append(str(path.relative_to(ROOT)))
            continue
        if change_title(path, title):
            changed += 1
        if has_craft:
            created += 1
        else:
            obtained += 1
    if missing:
        raise ValueError("Missing static detail pages: " + ", ".join(missing[:20]))

    # Give every newer item a unique crawlable HTML URL and pre-rendered title.
    # JavaScript continues to fill in the interactive recipe and acquisition tabs.
    category_names = {row[0]: row[1] for row in js_data("items-data.js", "MLG_ITEMS")["categories"]}
    template = (DETAILS / "new.html").read_text(encoding="utf-8")
    new_changed = 0
    for item in new:
        item_id, slug, name, *_ = item
        path = DETAILS / (slug + ".html")
        if path.exists() and "Generated by scripts/update_item_seo_titles.py" not in path.read_text(encoding="utf-8"):
            raise ValueError(f"Refusing to overwrite hand-written HTML: {path}")
        markup = build_new_item_page(template, item, category_names, recipes)
        previous_content = path.read_text(encoding="utf-8") if path.exists() else None
        if previous_content != markup:
            path.write_text(markup, encoding="utf-8")
        has_craft = bool(recipes.get(str(item_id)))
        title = "【マイクラ】 " + name + ("の作り方と使い方" if has_craft else "の入手方法")
        if change_title(path, title) or previous_content is None:
            new_changed += 1

    # Replace old query URLs in the submitted sitemap with the static URLs.
    sitemap_path = ROOT / "sitemap.xml"
    sitemap = sitemap_path.read_text(encoding="utf-8")
    for item in new:
        slug = item[1]
        old_url = f"https://mlabg.com/minecraft/strategy/items/detail/new.html?item={slug}"
        new_url = f"https://mlabg.com/minecraft/strategy/items/detail/{slug}.html"
        if sitemap.count(old_url) != 1:
            if sitemap.count(new_url) != 1:
                raise ValueError(f"Sitemap item URL missing or duplicated: {slug}")
        else:
            sitemap = sitemap.replace(old_url, new_url, 1)
    sitemap_path.write_text(sitemap, encoding="utf-8")

    # Preserve the generic query-based template for incoming older links.
    template_changed = change_title(
        DETAILS / "new.html", "【マイクラ】 追加アイテムの入手方法"
    )
    print(f"New items with individual HTML and sitemap URLs: {len(new)}; refreshed: {new_changed}.")
    print(
        f"Validated {len(old)} existing item pages; {created} crafting titles, "
        f"{obtained} acquisition titles; {changed} updated. "
        f"Dynamic 2026 additions: {len(new)}; template changed: {template_changed}."
    )


if __name__ == "__main__":
    main()
